// Command gen writes every generated face of the add-on ABI from the one place
// the ABI is authored, internal/addon/abi.
//
// Three outputs, and the reason there is a generator at all is that they are
// three views of one list:
//
//   - sdk/, the Go package an add-on imports and compiles for wasip1. Its
//     wasmimport declarations, its wrappers, its error values and its level
//     constants all come from abi.Functions, abi.Statuses and abi.LogLevels.
//   - docs/addon-abi.md's function table, between the generated markers. The
//     policy prose around it is written by hand; the table is not, because a
//     hand-maintained table of N functions beside N functions is a table that
//     describes N-1 of them. Written without the number on purpose: the first
//     draft of this comment said ten, twice, and there are eleven.
//
// Run it with `make abi-sdk`, or `make generate`, which is where sqlc and
// openapi also live. `make check-generate` re-runs it and fails on a diff, so a
// hand-edited SDK cannot survive CI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/DevOfPie/LinkCtrl/internal/addon/abi"
)

const (
	beginMarker = "<!-- BEGIN GENERATED: the function table -->"
	endMarker   = "<!-- END GENERATED -->"
)

func main() {
	root := flag.String("root", ".", "repository root to write into")
	flag.Parse()

	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "abi-sdk:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	for _, out := range []struct {
		path string
		gen  func() ([]byte, error)
	}{
		{filepath.Join(root, "sdk", "abi_gen.go"), goFile(constants)},
		{filepath.Join(root, "sdk", "abi_gen_wasip1.go"), goFile(wasip1)},
		{filepath.Join(root, "sdk", "abi_gen_other.go"), goFile(other)},
	} {
		src, err := out.gen()
		if err != nil {
			return fmt.Errorf("%s: %w", out.path, err)
		}
		if err := os.WriteFile(out.path, src, 0o644); err != nil { //nolint:gosec // G306: generated source, committed and world-readable like every other file here
			return err
		}
	}
	return docTable(filepath.Join(root, "docs", "addon-abi.md"))
}

func goFile(body func(*bytes.Buffer)) func() ([]byte, error) {
	return func() ([]byte, error) {
		var b bytes.Buffer
		body(&b)
		src, err := format.Source(b.Bytes())
		if err != nil {
			return nil, fmt.Errorf("the generator emitted source gofmt rejects: %w\n%s", err, b.String())
		}
		return src, nil
	}
}

func header(b *bytes.Buffer, constraint string) {
	b.WriteString("// Code generated by internal/addon/abi/gen. DO NOT EDIT.\n")
	b.WriteString("// Edit internal/addon/abi and run `make abi-sdk`.\n\n")
	if constraint != "" {
		b.WriteString("//go:build " + constraint + "\n\n")
	}
	b.WriteString("package sdk\n\n")
}

// constants is the part of the SDK that compiles for every platform: the version
// the SDK was generated against, the error values, and the log levels.
func constants(b *bytes.Buffer) {
	header(b, "")
	b.WriteString("import \"errors\"\n\n")

	comment(b, "", "ABIVersion is the ABI version this SDK was generated from. An add-on's "+
		"manifest declares ABIGeneration in its abi_version field; the host refuses a "+
		"module built against a generation it does not implement, before instantiating it.")
	fmt.Fprintf(b, "const ABIVersion = %q\n\n", abi.Version)
	comment(b, "", "ABIGeneration is the integer a manifest's abi_version field must carry for a "+
		"module built against this SDK.")
	fmt.Fprintf(b, "const ABIGeneration = %d\n\n", abi.Generation)

	comment(b, "", "The errors a host function can answer with. Every one is comparable with "+
		"errors.Is, and a status this SDK does not know arrives as an unwrapped error naming "+
		"the number — which is what a module built against an older SDK sees when a newer "+
		"host refuses it for a reason that did not exist yet.")
	b.WriteString("var (\n")
	for _, s := range abi.Statuses {
		comment(b, "\t", capitalize(s.Doc)+".")
		fmt.Fprintf(b, "\t%s = errors.New(%q)\n", s.Go, "linkctrl: "+s.Doc)
	}
	b.WriteString(")\n\n")

	comment(b, "", "The levels Log accepts. Anything else is ErrInvalid.")
	b.WriteString("const (\n")
	for _, l := range abi.LogLevels {
		fmt.Fprintf(b, "\tLevel%s = %q\n", capitalize(l), l)
	}
	b.WriteString(")\n\n")

	b.WriteString("// statusError maps a negative return value onto one of the errors above.\n")
	b.WriteString("func statusError(n int32) error {\n\tswitch n {\n")
	for _, s := range abi.Statuses {
		fmt.Fprintf(b, "\tcase %d:\n\t\treturn %s\n", s.Status, s.Go)
	}
	b.WriteString("\t}\n\treturn errors.New(\"linkctrl: the host refused with a status this SDK does not know\")\n}\n")
}

// wasip1 is the real SDK: the imports the host resolves, and the wrappers.
func wasip1(b *bytes.Buffer) {
	header(b, "wasip1 && wasm")
	b.WriteString("import (\n\t\"runtime\"\n\t\"unsafe\"\n)\n\n")

	for _, f := range abi.Functions {
		fmt.Fprintf(b, "//go:wasmimport %s %s\n", abi.HostModule, f.Name)
		b.WriteString("//go:noescape\n")
		fmt.Fprintf(b, "func %s(%s) int32\n\n", rawName(f), rawParams(f))
	}

	for _, f := range abi.Functions {
		docComment(b, f)
		out, hasOut := f.Out()
		fmt.Fprintf(b, "func %s(%s) %s {\n", f.Go, goParams(f), goResults(f))

		call := func(indent string) {
			fmt.Fprintf(b, "%sn := %s(%s)\n", indent, rawName(f), rawArgs(f))
			for _, p := range f.Params {
				if p.Kind.Out() {
					fmt.Fprintf(b, "%sruntime.KeepAlive(buf)\n", indent)
					continue
				}
				if p.Kind == abi.String || p.Kind == abi.Bytes {
					fmt.Fprintf(b, "%sruntime.KeepAlive(%s)\n", indent, p.Name)
				}
			}
		}

		if !hasOut {
			call("\t")
			b.WriteString("\tif n < 0 {\n\t\treturn statusError(n)\n\t}\n\treturn nil\n}\n\n")
			continue
		}

		zero := `""`
		if out.Kind == abi.OutBytes {
			zero = "nil"
		}
		b.WriteString("\tbuf := make([]byte, initialBuffer)\n")
		b.WriteString("\tfor attempt := 0; attempt < growthAttempts; attempt++ {\n")
		call("\t\t")
		fmt.Fprintf(b, "\t\tif n < 0 {\n\t\t\treturn %s, statusError(n)\n\t\t}\n", zero)
		if out.Kind == abi.OutBytes {
			b.WriteString("\t\tif int(n) <= len(buf) {\n\t\t\treturn buf[:n:n], nil\n\t\t}\n")
		} else {
			b.WriteString("\t\tif int(n) <= len(buf) {\n\t\t\treturn string(buf[:n]), nil\n\t\t}\n")
		}
		b.WriteString("\t\tbuf = make([]byte, n)\n\t}\n")
		fmt.Fprintf(b, "\treturn %s, ErrInternal\n}\n\n", zero)
	}
}

// other is the same API for every platform that is not wasip1/wasm, so the
// package builds, vets and lints natively and a consumer's own tests compile.
func other(b *bytes.Buffer) {
	header(b, "!(wasip1 && wasm)")
	for _, f := range abi.Functions {
		docComment(b, f)
		out, hasOut := f.Out()
		fmt.Fprintf(b, "func %s(%s) %s {\n", f.Go, goParams(f), goResults(f))
		if !hasOut {
			b.WriteString("\treturn errNotWasm\n}\n\n")
			continue
		}
		zero := `""`
		if out.Kind == abi.OutBytes {
			zero = "nil"
		}
		fmt.Fprintf(b, "\treturn %s, errNotWasm\n}\n\n", zero)
	}
}

func rawName(f abi.Function) string { return "wasm" + f.Go }

func rawParams(f abi.Function) string {
	var parts []string
	for _, p := range f.Params {
		switch p.Kind {
		case abi.Int32:
			parts = append(parts, p.Name+" int32")
		case abi.Int64:
			parts = append(parts, p.Name+" int64")
		default:
			parts = append(parts, p.Name+"Ptr unsafe.Pointer", p.Name+"Len uint32")
		}
	}
	return strings.Join(parts, ", ")
}

func rawArgs(f abi.Function) string {
	var parts []string
	for _, p := range f.Params {
		switch p.Kind {
		case abi.Int32, abi.Int64:
			parts = append(parts, p.Name)
		case abi.String:
			parts = append(parts, "stringPtr("+p.Name+")", "uint32(len("+p.Name+"))")
		case abi.Bytes:
			parts = append(parts, "bytesPtr("+p.Name+")", "uint32(len("+p.Name+"))")
		default:
			parts = append(parts, "bytesPtr(buf)", "uint32(len(buf))")
		}
	}
	return strings.Join(parts, ", ")
}

func goParams(f abi.Function) string {
	var parts []string
	for _, p := range f.Params {
		if p.Kind.Out() {
			continue
		}
		parts = append(parts, p.Name+" "+p.Kind.GoType())
	}
	return strings.Join(parts, ", ")
}

func goResults(f abi.Function) string {
	out, ok := f.Out()
	if !ok {
		return "error"
	}
	return "(" + out.Kind.GoType() + ", error)"
}

func docComment(b *bytes.Buffer, f abi.Function) {
	comment(b, "", f.Doc)
	var params []string
	for _, p := range f.Params {
		if p.Kind.Out() {
			continue
		}
		params = append(params, p.Name+" is "+p.Doc)
	}
	if len(params) > 0 {
		b.WriteString("//\n")
		comment(b, "", strings.Join(params, "; ")+".")
	}
	b.WriteString("//\n")
	// The milestone in Function.BackedBy is deliberately not emitted. This
	// comment ends up in another repository's editor, where a LinkCtrl milestone
	// number is a string with no referent — the same reason CHANGELOG.md carries
	// none. Whether a host implements the function is the fact a consumer needs,
	// and it is a runtime answer rather than a build-time one.
	status := "implemented since this version"
	if !f.Live {
		status = "declared, and not implemented by every host: a host without it " +
			"answers ErrNotAvailable, which a module may branch on"
	}
	comment(b, "", "ABI: "+abi.HostModule+"."+f.Name+", since "+f.Since+"; "+status+".")
	// The permission is emitted because it is the one thing a consumer cannot
	// discover from the signature and cannot recover from the error: ErrDenied says
	// the host refused, and only this says which line of the manifest was missing.
	if f.Requires != "" {
		b.WriteString("//\n")
		comment(b, "", "Requires the "+f.Requires+" permission, declared in this add-on's "+
			"manifest. A module that did not declare it gets ErrDenied, whether or not the "+
			"host implements the function.")
	}
	if f.Deprecated != "" {
		b.WriteString("//\n")
		comment(b, "", "Deprecated: "+f.Deprecated+" It may be removed in ABI "+f.RemovedNotBefore+" or later.")
	}
}

// comment wraps a paragraph into // lines at 79 columns including the prefix,
// which is what gofmt leaves alone and what the rest of this repository reads
// like.
func comment(b *bytes.Buffer, indent, text string) {
	const width = 76
	line := indent + "//"
	for _, word := range strings.Fields(text) {
		if len(line)+1+len(word) > width && line != indent+"//" {
			b.WriteString(line + "\n")
			line = indent + "//"
		}
		line += " " + word
	}
	if line != indent+"//" {
		b.WriteString(line + "\n")
	}
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// docTable rewrites the generated region of docs/addon-abi.md in place, leaving
// every hand-written line around it untouched.
func docTable(path string) error {
	current, err := os.ReadFile(path) //nolint:gosec // G304: a path this repository's own Makefile passes
	if err != nil {
		return err
	}
	text := string(current)
	begin := strings.Index(text, beginMarker)
	end := strings.Index(text, endMarker)
	if begin < 0 || end < 0 || end < begin {
		return fmt.Errorf("%s: the generated markers are missing or out of order; expected %q then %q",
			path, beginMarker, endMarker)
	}

	var b strings.Builder
	b.WriteString(beginMarker + "\n\n")
	fmt.Fprintf(&b, "The ABI is **%s**, generation **%d**, and this host loads generation %d or newer.\n\n",
		abi.Version, abi.Generation, abi.MinimumGeneration)

	b.WriteString("| Function | Since | Requires | Status | What it is |\n" +
		"| --- | --- | --- | --- | --- |\n")
	for _, f := range abi.Functions {
		status := "**live**"
		if !f.Live {
			status = "declared, refused"
		}
		if f.Deprecated != "" {
			status += " · **deprecated**, removable in " + f.RemovedNotBefore
		}
		requires := "—"
		if f.Requires != "" {
			requires = "`" + f.Requires + "`"
		}
		fmt.Fprintf(&b, "| `%s`<br>`sdk.%s(%s)` | %s | %s | %s | %s |\n",
			f.Name, f.Go, goParams(f), f.Since, requires, status, oneLine(f.Doc))
	}

	b.WriteString("\n### Permissions\n\nAn add-on declares what it needs in its manifest's " +
		"`permissions` array, and the host refuses a call whose permission is not there — " +
		"before it refuses one it has not implemented, so a module that declared nothing " +
		"cannot use the availability status to find out what a host can do. The vocabulary " +
		"is closed: a token outside it refuses the add-on at load.\n\n" +
		"| Permission | Grantable | Is |\n| --- | --- | --- |\n")
	for _, p := range abi.Permissions {
		grantable := "yes"
		if !p.Grantable {
			grantable = "**no host grants it yet**"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", p.Name, grantable, oneLine(p.Doc))
	}

	b.WriteString("\n### Statuses\n\nEvery function returns one `i32`: a length or zero on success, " +
		"one of these on failure.\n\n| Status | SDK | Means |\n| --- | --- | --- |\n")
	for _, s := range abi.Statuses {
		fmt.Fprintf(&b, "| `%d` | `sdk.%s` | %s |\n", s.Status, s.Go, capitalize(s.Doc))
	}

	b.WriteString("\n### Records\n\nA record crosses the boundary as a JSON object.\n")
	for _, r := range abi.Records {
		fmt.Fprintf(&b, "\n#### `%s`\n\n%s\n\n", r.Name, oneLine(r.Doc))
		if r.ClickDerived {
			b.WriteString("**Bound by `click_events`.** Every field below is one that table may " +
				"carry, and a test reads the column list out of the migration to prove it.\n\n")
		}
		if r.PrefixedCookies {
			b.WriteString("**Cookies are prefix-filtered.** An add-on sees the cookies whose names " +
				"begin with one of the `cookie_prefixes` its manifest declares, and a declared " +
				"prefix has to begin with the add-on's own name — so no prefix an add-on may " +
				"declare reaches a cookie of the host's, and this instance's session cookie is " +
				"not among the ones it can ask for.\n\n")
		}
		b.WriteString("| Field | Type | Notes |\n| --- | --- | --- |\n")
		for _, f := range r.Fields {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", f.Name, f.Type, capitalize(f.Doc))
		}
	}

	b.WriteString("\n")
	updated := text[:begin] + b.String() + text[end:]
	return os.WriteFile(path, []byte(updated), 0o644) //nolint:gosec // G306: documentation, committed and world-readable
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
