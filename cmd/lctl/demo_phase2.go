// attributeSplitClicks spreads the weighted link's existing clicks across its
// arms.
//
// **This is one of the places that deliberately goes around the service layer,
// and it says so here.** The clicks it is editing were never produced by a
// service either — demoClicks writes them with COPY, because a month of history
// cannot be generated by making a month of requests — so there is no redirect to
// route and no `destination_id` for a redirect to have chosen. The alternative
// is a demo whose split test has arms and no result, which is exactly the empty
// page m36.md calls "a coin flip with extra steps".
//
// Bucketed on the visitor, not on the click. Two properties come out of that
// and both are wanted. It is what a real split test does — somebody who comes
// back the same day sees the same arm, and an arm that changed under them would
// make the demo's own numbers a lie about how the feature behaves. And it is
// deterministic across runs, which bucketing on the click's id was not:
// demoClicks writes each row with a fresh uuid.NewV7, so the same seeded dataset
// hashed differently every time and the per-day breakdown gained and lost rows
// between two runs of `make demo-update`. The visitor hash is derived from the
// day and the visitor index, both of which come from the seeded PRNG.
//
// The arms are weighted 60 and 30 and the bucketing is 60/90ths and 30/90ths of
// the hash space, so the observed shares land near the configured ones without
// being identical to them — which is what a real test looks like and what makes
// the "configured versus observed" reading on the page worth having.
//
// Bot clicks are left unattributed. They are excluded from every rollup anyway,
// and attributing them would be claiming a crawler was part of the test.
func (s *demoSeeder) attributeSplitClicks(ctx context.Context, linkID uuid.UUID) error {
	const q = `
		WITH arms AS (
		    SELECT d.id, d.weight,
		           sum(d.weight) OVER (ORDER BY d.position
		                               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS upper,
		           coalesce(sum(d.weight) OVER (ORDER BY d.position
		                               ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS lower,
		           sum(d.weight) OVER () AS total
		      FROM destinations d
		      JOIN routing_rules rr ON rr.destination_id = d.id
		     WHERE d.link_id = $1 AND d.deleted_at IS NULL
		       AND rr.kind = 'weighted' AND rr.enabled
		)
		UPDATE click_events ce
		   SET destination_id = a.id
		  FROM arms a
		 WHERE ce.link_id = $1
		   AND NOT ce.is_bot
		   AND (('x' || substr(md5(ce.visitor_hash), 1, 8))::bit(32)::bigint & 2147483647) % a.total
		       >= a.lower
		   AND (('x' || substr(md5(ce.visitor_hash), 1, 8))::bit(32)::bigint & 2147483647) % a.total
		       <  a.upper`
	if _, err := s.pool.Exec(ctx, q, linkID); err != nil {
		return fmt.Errorf("attribute split clicks on /%s: %w", demoWeightedLink, err)
	}
	return nil
}

