// seedAPIKeys mints the demo's keys and rotates one of them.
//
// The rotation goes through the real path rather than through SQL, and that is
// the point of doing it at all: `Rotate` refuses any actor that is not a key, so
// the seeder has to authenticate with the token it was just handed and act as the
// credential. A seeder that wrote `successor_id` directly would be showing a
// state the product might no longer produce.
//
// The grace window is the maximum the service allows, and the reason is the demo
// rather than the product. `make demo-update` runs once per milestone, and with
// the default hour the predecessor would show *rotated* for an hour and *revoked*
// for however long followed — so the state the milestone exists to show would be
// missing from the page most of the time somebody looked at it.
func (s *demoSeeder) seedAPIKeys(ctx context.Context) error {
	rotated := 0
	for _, spec := range demoAPIKeys() {
		in := auth.CreateAPIKeyInput{
			Name: spec.name, Scopes: spec.scopes, OrgWide: spec.orgWide,
		}
		if spec.pinned {
			org := s.owner.OrgID
			in.OrganizationID = &org
		}
		created, err := s.keys.Create(ctx, s.owner, in)
		if err != nil {
			return fmt.Errorf("create api key %q: %w", spec.name, err)
		}
		if !spec.rotate {
			continue
		}

		// Acting as the key, because only a key rotates and only itself.
		actor, err := s.keys.Authenticate(ctx, created.Key)
		if err != nil {
			return fmt.Errorf("authenticate as %q to rotate it: %w", spec.name, err)
		}
		if _, err := s.keys.Rotate(ctx, actor, auth.RotateAPIKeyInput{
			Grace: auth.MaxRotationGrace,
		}); err != nil {
			return fmt.Errorf("rotate api key %q: %w", spec.name, err)
		}
		rotated++
	}

	// Authenticate buffers a last_used_at write, and the demo's key service is
	// never started, so nothing would ever flush it. Flushed here so the list
	// shows the rotated key as used rather than as never touched — which is the
	// truth, since it made the rotation request itself.
	if err := s.keys.FlushUsage(ctx); err != nil {
		return fmt.Errorf("flush api key usage: %w", err)
	}

	fmt.Fprintf(os.Stderr, "api keys: %d (%d rotated)\n", len(demoAPIKeys()), rotated)
	return nil
}

// demoDomains are the hostnames the demo registers, one per workspace.
//
// **Two, and in different workspaces, because one would show nothing.** A single
// registered hostname makes the domains page a list; two, owned by the two
// workspaces the demo already has, make it the thing M39 built — switch
// workspace and the list changes, because a hostname belongs to exactly one of
// them. That is also the only way a reader sees the ownership rule without
// having a second account to be refused with.
//
// Both are `.example` names, which RFC 2606 reserves and which therefore cannot
// resolve for anybody. That matters more here than it looks: nothing on the
// instance serves these, and a demo that registered a name somebody owns would
// be a demo suggesting it had been claimed.
func demoDomains() []struct {
	workspace string
	hostname  string
	// verify says whether the seeder publishes this hostname's challenge record
	// and checks it (M40). Exactly one does, and the asymmetry is the whole
	// point: a list where both are verified shows one state, a list where
	// neither is shows the state M39 shipped, and only a list with one of each
	// shows what verification decides.
	verify bool
} {
	return []struct {
		workspace string
		hostname  string
		verify    bool
	}{
		{workspace: "", hostname: "go.linkctrl.example", verify: true},
		{workspace: demoWorkspace2Slug, hostname: "camp.linkctrl.example"},
	}
}

// seedDomains registers a hostname for each workspace (M39).
//
// Through link.Service.RegisterDomain, like everything else here, so the demo
// exercises the ownership check and the audit events rather than writing rows
// that look like its output. Each registration is stored unverified and nothing
// on the instance serves it — which is what the page says, and what the demo has
// to show rather than contradict.
func (s *demoSeeder) seedDomains(ctx context.Context) error {
	for _, d := range demoDomains() {
		actor := s.owner
		if d.workspace != "" {
			var wsID uuid.UUID
			if err := s.pool.QueryRow(ctx,
				`SELECT id FROM workspaces WHERE organization_id = $1 AND slug = $2`,
				s.owner.OrgID, d.workspace).Scan(&wsID); err != nil {
				return fmt.Errorf("find workspace %q for %s: %w", d.workspace, d.hostname, err)
			}
			here, err := s.actAs(ctx, s.owner.Email, wsID)
			if err != nil {
				return err
			}
			actor = here
		}
		registered, err := s.link.RegisterDomain(ctx, actor, d.hostname)
		if err != nil {
			return fmt.Errorf("register %s: %w", d.hostname, err)
		}
		if !d.verify {
			// Left as M39 shipped it: registered, with a record to publish and
			// nothing served. The page has to be able to show this state, and a
			// demo where every hostname works would never show it.
			fmt.Fprintf(os.Stderr, "domain %s: registered to %s, unverified\n",
				d.hostname, actor.WorkspaceID)
			continue
		}
		// "Publish" the record, then verify through the service — the real
		// check, against a resolver that answers for a name nobody can own.
		if registered.Verification == nil {
			return fmt.Errorf("registering %s produced no challenge", d.hostname)
		}
		demoPublishedRecords[registered.Verification.RecordName] = registered.Verification.RecordData
		verified, err := s.link.VerifyDomain(ctx, actor, registered.ID)
		if err != nil {
			return fmt.Errorf("verify %s: %w", d.hostname, err)
		}
		// A root for the bare hostname, so the demo shows the per-domain setting
		// rather than only the instance-wide one. Through the service, so the
		// destination goes through the blocking tiers like any other.
		if _, err := s.link.SetDomainRootRedirect(ctx, actor, verified.ID,
			"https://example.com/linkctrl-demo"); err != nil {
			return fmt.Errorf("set root redirect for %s: %w", d.hostname, err)
		}
		// And one link on it, which is what makes the hostname visible anywhere
		// other than the domains page: the links list shows its short URL built
		// from this hostname rather than from the instance's own.
		//
		// Aged and given traffic like the catalogue's, for the reason
		// seedGatedLinks gives: this was the fifth of the five links carrying the
		// instant of the seed, and between them they were the whole of the
		// dashboard's *Recent links* — five rows reading zero clicks (F165). The
		// weighted generator rather than an exact count, because nothing compares
		// this link's total against anything and a curve is what its own detail
		// page has charts for.
		spring := []demoLink{{alias: "spring", weight: 9, from: 12, age: 13}}
		created, err := s.link.Create(ctx, actor, link.CreateInput{
			URL:      "https://example.com/campaigns/spring",
			Alias:    spring[0].alias,
			Title:    "Spring campaign, on this workspace's own hostname",
			DomainID: &verified.ID,
		})
		if err != nil {
			return fmt.Errorf("create a link on %s: %w", d.hostname, err)
		}
		if _, err := s.pool.Exec(ctx,
			`UPDATE links SET created_at = $2, updated_at = $2 WHERE id = $1`,
			created.ID, s.now.AddDate(0, 0, -spring[0].age)); err != nil {
			return fmt.Errorf("backdate /%s: %w", spring[0].alias, err)
		}
		springClicks, err := demoClicks(ctx, s.pool, actor.WorkspaceID.String(),
			spring, map[int]uuid.UUID{0: created.ID}, s.opt, s.now)
		if err != nil {
			return fmt.Errorf("click history for /%s: %w", spring[0].alias, err)
		}
		fmt.Fprintf(os.Stderr, "domain %s: registered to %s, verified, 1 link, %d clicks\n",
			d.hostname, actor.WorkspaceID, springClicks)
	}
	// Back where the demo opens, exactly as seedSecondWorkspace does.
	if _, err := s.actAs(ctx, s.owner.Email, s.owner.WorkspaceID); err != nil {
		return err
	}
	return nil
}

